"""A patch's switches (patch/<game>/options.toml): one byte each, in file order, in a block at the
start of the patch's payload. Generates the patch's `options.hpp` and the manifest the app's options
menu reads and writes guest memory from (docs/app.md, "Options").
"""

from __future__ import annotations

import json
import tomllib
from dataclasses import dataclass
from pathlib import Path

from z3dmods import games

# The manifest's name inside a game's installed mod folder.
MANIFEST = "z3d-options.json"


@dataclass(frozen=True)
class Option:
    id: str
    # The member of the patch's Options struct.
    field: str
    label: str
    default: bool


def load(repo: Path, game: str) -> list[Option]:
    path = repo / "patch" / game / "options.toml"
    entries = tomllib.loads(path.read_text())["option"]
    return [Option(e["id"], e["field"], e["label"], e["default"]) for e in entries]


def generate(repo: Path, game: str, out: Path) -> Path:
    """The patch's view: `options()` returns the block; link.ld keeps `.options` first in the payload."""
    lines = [f"// Generated by tools/z3dmods/options.py from patch/{game}/options.toml; do not edit.",
             "#pragma once", "", "#include <stdint.h>", "", f"namespace z3dmods::{game} {{", "",
             "struct Options {"]
    lines += [f"  uint8_t {option.field} = {int(option.default)};" for option in load(repo, game)]
    lines += ["};", "",
              '[[gnu::section(".options"), gnu::used]] inline constinit volatile Options optionsBlock;', "",
              "inline const volatile Options &options() {", "  return optionsBlock;", "}", "",
              f"}} // namespace z3dmods::{game}", ""]
    out.mkdir(parents=True, exist_ok=True)
    header = out / "options.hpp"
    header.write_text("\n".join(lines))
    return header


def manifest(repo: Path, game: str, address: int) -> str:
    """`address` is the block's guest address: the payload's start. "screens" tells the app's
    overlay layout (app/src/screen_overlay.hpp) which touch screen is up."""
    items = [{"id": o.id, "label": o.label, "default": o.default} for o in load(repo, game)]
    document: dict[str, object] = {"address": address, "options": items}
    layout = games.layout(repo, game)
    if layout.active_screen is not None:
        document["screens"] = {"active": layout.active_screen, "table": layout.screens,
                               "count": layout.screen_count, "main": layout.main_screen,
                               "black": layout.black_screen, "play": layout.play_pointer,
                               "cutscene": layout.cutscene_state}
    return json.dumps(document, indent=2) + "\n"
