"""The block a patch and the app share for the item slots (docs/plans/pc-controls-hud.md): the app's
pad owner writes the slots held this frame, the patch writes which pad table the game wants and
what each slot holds. One layout, here: the patch gets a generated `slot_link.hpp`, and the app
the address of each field in the install's manifest (`"link"` in z3d-options.json)."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

SLOTS = 11


@dataclass(frozen=True)
class Field:
    name: str
    kind: str
    bytes: int
    count: int
    comment: str


FIELDS = (
    Field("held", "uint16_t", 2, 1, "app: the slots held now, bit n for slot n"),
    Field("mode", "uint8_t", 1, 1, "patch: the PadMode the game is in"),
    Field("items", "uint8_t", 1, SLOTS, "patch: the item each slot holds, kSlotEmpty for none"),
    Field("songs", "uint8_t", 1, SLOTS, "patch: the song each slot plays plus one, 0 for none"),
    Field("lanes", "uint8_t", 1, SLOTS, "patch: the index in the game's button arrays of the item button a slot is on, 0 for none"),
)

# PadMode, in the app's order (app/src/pad_input.hpp).
MODES = ("ByName", "Play", "Assign")


def _offsets() -> dict[str, int]:
    offsets, at = {}, 0
    for field in FIELDS:
        at = (at + field.bytes - 1) // field.bytes * field.bytes
        offsets[field.name] = at
        at += field.bytes * field.count
    return offsets


def generate(out: Path) -> Path:
    """The patch's view: `slotLink()` is the block; link.ld gives `.link` its own section."""
    lines = ["// Generated by tools/z3dmods/slot_link.py; do not edit.", "#pragma once", "",
             "#include <stddef.h>", "#include <stdint.h>", "", "namespace z3dmods {", "",
             f"inline constexpr uint32_t kSlotCount = {SLOTS};",
             "inline constexpr uint8_t kSlotEmpty = 0xFF;", "",
             "enum class PadMode : uint8_t { " + ", ".join(MODES) + " };", "", "struct SlotLink {"]
    for field in FIELDS:
        array = f"[{field.count}]" if field.count > 1 else ""
        lines.append(f"  {field.kind} {field.name}{array}; // {field.comment}")
    lines += ["};"]
    lines += [f"static_assert(offsetof(SlotLink, {name}) == {offset});" for name, offset in _offsets().items()]
    lines += ["", '[[gnu::section(".link"), gnu::used]] inline constinit volatile SlotLink slotLinkBlock{};', "",
              "inline volatile SlotLink &slotLink() {", "  return slotLinkBlock;", "}", "",
              "} // namespace z3dmods", ""]
    out.mkdir(parents=True, exist_ok=True)
    header = out / "slot_link.hpp"
    header.write_text("\n".join(lines))
    return header


def manifest(address: int) -> dict[str, int]:
    """Each field's guest address, and how many slots there are."""
    return {name: address + offset for name, offset in _offsets().items()} | {"slots": SLOTS}
